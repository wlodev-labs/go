package zerolog

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/cockroachdb/errors"
	"github.com/rs/zerolog"
)

// New returns a logger with timestamp, stack and caller fields. With isDev it
// writes human-readable console output, otherwise JSON. Both go to stdout with
// RFC3339 timestamps.
func New(isDev bool) zerolog.Logger {
	zerolog.TimeFieldFormat = time.RFC3339
	var logger zerolog.Logger
	if isDev {
		logger = zerolog.New(zerolog.ConsoleWriter{
			Out:        os.Stdout,
			TimeFormat: time.RFC3339,
		})
	} else {
		logger = zerolog.New(os.Stdout)
	}

	return logger.With().
		Timestamp().
		Stack().
		Caller().
		Logger()
}

var stackIgnoredPaths = []string{
	"/usr/local/go/src/",
	"/src/runtime/",
	"<autogenerated>",
	// Dependencies live in versioned module directories, both in the module
	// cache (.../pkg/mod/github.com/go-chi/chi/v5@v5.2.1/mux.go) and in
	// -trimpath builds (github.com/go-chi/chi/v5@v5.2.1/mux.go).
	"@v",
}

// oapi-codegen writes *.gen.go. Its frames are only router plumbing between
// the middleware and the handler.
var stackIgnoredFileSuffixes = []string{
	".gen.go",
	"_gen.go",
	".pb.go",
}

// ErrorStackMarshaler returns the stack trace attached to err by
// github.com/cockroachdb/errors as "Function path:line" strings, innermost
// frame first. It keeps only frames from the application's own hand-written
// code: the Go runtime and standard library, dependency modules and generated
// files (*.gen.go, *_gen.go, *.pb.go) are left out. It returns nil when err
// carries no stack trace. Assign it to zerolog.ErrorStackMarshaler.
func ErrorStackMarshaler(err error) any {
	st := errors.GetReportableStackTrace(err)
	if st == nil || len(st.Frames) == 0 {
		return nil
	}

	frames := make([]string, 0, len(st.Frames))
	for i := len(st.Frames) - 1; i >= 0; i-- {
		f := st.Frames[i]
		if strings.HasPrefix(f.Function, "runtime.") {
			continue
		}

		path := f.AbsPath
		if path == "" {
			path = f.Filename
		}

		if isIgnoredStackPath(path) {
			continue
		}
		frames = append(frames, fmt.Sprintf("%s %s:%d", f.Function, path, f.Lineno))
	}
	return frames
}

func isIgnoredStackPath(path string) bool {
	for _, ignoredPath := range stackIgnoredPaths {
		if strings.Contains(path, ignoredPath) {
			return true
		}
	}
	for _, suffix := range stackIgnoredFileSuffixes {
		if strings.HasSuffix(path, suffix) {
			return true
		}
	}
	return false
}
